CREATE TABLE IF NOT EXISTS "public"."view_count" (
    "id" bigint NOT NULL,
    "username" "text" NOT NULL,
    "views_count" bigint DEFAULT '0'::bigint
);


ALTER TABLE "public"."view_count" OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."record_view"("p_username" "text", "p_initial_views" bigint DEFAULT 1) RETURNS SETOF "public"."view_count"
    LANGUAGE "sql"
    AS $$
    INSERT INTO public.view_count AS vc (
        username,
        views_count
    )
    VALUES (
        p_username,
        p_initial_views
    )
    ON CONFLICT (username)
    DO UPDATE SET
        views_count = vc.views_count + 1
    RETURNING vc.*;
$$;


ALTER FUNCTION "public"."record_view"("p_username" "text", "p_initial_views" bigint) OWNER TO "postgres";


ALTER TABLE "public"."view_count" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "public"."view_count_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);



